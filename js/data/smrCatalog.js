// Позициите, създадени преди въвеждането на полето category (или въведени ръчно),
// нямат записана категория — разпознаваме я по описанието, иначе падат в „Други“.
export function categoryForDescription(description) {
  if (!description) return '';
  return CATEGORY_BY_DESCRIPTION.get(String(description).trim().toLowerCase()) || '';
}

export function resolveCategory(position) {
  return (position && position.category) || categoryForDescription(position && position.description) || OTHER_CATEGORY;
}
